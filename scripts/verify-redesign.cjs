const { chromium } = require('playwright');
const assert = require('node:assert/strict');

(async()=>{
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  const errors=[];
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:4322/',{waitUntil:'networkidle'});
  assert.match(await page.locator('.hero-photo img').getAttribute('src'),/hero2/);
  assert.equal(await page.locator('.cover-subtitle').evaluate(el=>el.getBoundingClientRect().height<=parseFloat(getComputedStyle(el).lineHeight)*1.2),true,'desktop subtitle should stay on one line');
  assert.deepEqual(await page.locator('.room-condition').evaluateAll(nodes=>nodes.map(node=>node.dataset.condition)),['A','B','C','D']);
  assert.equal(await page.locator('#experiment').count(),0);
  assert.equal(await page.locator('#methodology').count(),0);
  await page.locator('.room-condition[data-condition="C"]').click();
  await page.waitForTimeout(350);
  assert.equal(await page.locator('.explore-stage').getAttribute('data-room-light'),'cool');
  await page.locator('#listen').scrollIntoViewIfNeeded();
  await page.locator('[data-listening-theme="white"]').click();
  assert.equal(await page.locator('#listen').getAttribute('data-theme'),'white');
  await page.locator('[data-select="compare"]').click();
  assert.equal(await page.locator('[data-view="spectrogram"]').getAttribute('aria-selected'),'true');
  assert.equal(await page.locator('.spectrogram-row').count(),2);
  await page.locator('#gallery').scrollIntoViewIfNeeded();
  await page.locator('[data-gallery-next]').click();
  await page.waitForTimeout(450);
  assert.equal(await page.locator('[data-gallery-current]').textContent(),'2');
  await page.screenshot({path:'/tmp/sound-space-desktop.png',fullPage:true});
  const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
  mobile.on('console',message=>{if(message.type()==='error')errors.push(`mobile: ${message.text()}`);});
  mobile.on('pageerror',error=>errors.push(`mobile: ${error.message}`));
  await mobile.goto('http://127.0.0.1:4322/',{waitUntil:'networkidle'});
  assert.equal(await mobile.locator('.room-condition').count(),4);
  assert.equal(await mobile.locator('.gallery-slide').count(),4);
  assert.equal(await mobile.locator('body').evaluate(el=>el.scrollWidth<=innerWidth+1),true,'mobile page should not overflow horizontally');
  await mobile.screenshot({path:'/tmp/sound-space-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Redesign verification passed: desktop, interactions, comparison, gallery and mobile.');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
