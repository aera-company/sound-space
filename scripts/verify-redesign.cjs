const { chromium } = require('playwright');
const assert = require('node:assert/strict');

(async()=>{
  const siteUrl=process.env.SITE_URL||'http://127.0.0.1:4322/';
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  const errors=[];
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(siteUrl,{waitUntil:'networkidle'});
  assert.deepEqual(await page.locator('.masthead nav a').allTextContents(),['Conditions','Lighting','Soundscape','Videos','Photos']);
  assert.equal(await page.locator('.masthead').evaluate(el=>Math.round(el.getBoundingClientRect().width)===innerWidth),true,'desktop masthead should span the viewport');
  assert.match(await page.locator('.hero-photo img').getAttribute('src'),/hero-cover/);
  assert.equal(await page.locator('#page-title').evaluate(el=>parseFloat(getComputedStyle(el).fontSize)<=54),true,'hero title should use the reduced type size');
  assert.equal(await page.locator('#analysis-heading').textContent(),'Soundscape');
  assert.equal(await page.locator('#light-heading').textContent(),'Lighting');
  assert.equal((await page.locator('#film-heading').innerText()).replaceAll('\n',' / '),'A different tempo / A different light / The same space');
  const sectionTitleStyles=await page.locator('#explore-heading,#light-heading,#analysis-heading,#film-heading,#gallery-heading').evaluateAll(nodes=>nodes.map(node=>({size:Math.round(parseFloat(getComputedStyle(node).fontSize)),weight:getComputedStyle(node).fontWeight,family:getComputedStyle(node).fontFamily})));
  assert.equal(new Set(sectionTitleStyles.map(style=>style.size)).size,1,'section titles should share one size');
  assert.equal(sectionTitleStyles.every(style=>style.weight==='600'&&!/Georgia|Times/i.test(style.family)),true,'section titles should use the same semibold sans-serif');
  assert.equal(await page.locator('.cover-subtitle').evaluate(el=>el.getBoundingClientRect().height<=parseFloat(getComputedStyle(el).lineHeight)*1.2),true,'desktop subtitle should stay on one line');
  assert.deepEqual(await page.locator('.room-condition').evaluateAll(nodes=>nodes.map(node=>node.dataset.condition)),['1','2','3','4']);
  assert.deepEqual(await page.locator('.room-condition strong').allTextContents(),['Warm + Slow','Warm + Fast','Cool + Slow','Cool + Fast']);
  assert.equal((await page.locator('#explore .section-line').textContent()).includes('Explore room'),false);
  const conditionLayout=await page.locator('.explore-stage').evaluate(stage=>{const media=stage.querySelector('.room-media').getBoundingClientRect();const cards=stage.querySelector('.room-conditions').getBoundingClientRect();return{sameTop:Math.abs(media.top-cards.top)<=1,sameHeight:Math.abs(media.height-cards.height)<=1,touching:Math.abs(cards.left-media.right)<=1};});
  assert.deepEqual(conditionLayout,{sameTop:true,sameHeight:true,touching:true},'condition photograph and all four cards should form one continuous desktop frame');
  assert.equal(await page.locator('.room-photo-warm').evaluate(el=>getComputedStyle(el).objectFit),'contain','section 02 photograph should be shown in full');
  assert.equal(await page.locator('.choice-tempo').first().evaluate(el=>!/Georgia|Times/i.test(getComputedStyle(el).fontFamily)),true,'audio typography should use sans-serif');
  assert.equal(await page.locator('#experiment').count(),0);
  assert.equal(await page.locator('#methodology').count(),0);
  assert.deepEqual(await page.locator('.light-triptych figure>div').evaluateAll(nodes=>nodes.map(node=>Math.round(node.getBoundingClientRect().width/node.getBoundingClientRect().height*100))),[100,100,100]);
  await page.locator('.room-condition[data-condition="3"]').click();
  await page.waitForTimeout(350);
  assert.equal(await page.locator('.explore-stage').getAttribute('data-room-light'),'cool');
  await page.locator('#listen').scrollIntoViewIfNeeded();
  await page.locator('[data-listening-theme="white"]').click();
  assert.equal(await page.locator('#listen').getAttribute('data-theme'),'white');
  await page.locator('[data-select="compare"]').click();
  assert.equal(await page.locator('[data-view="spectrogram"]').getAttribute('aria-selected'),'true');
  assert.equal(await page.locator('.spectrogram-row').count(),2);
  await page.locator('#gallery').scrollIntoViewIfNeeded();
  assert.equal(await page.locator('.gallery-slide').count(),11);
  assert.equal(await page.locator('.gallery-slide img').first().evaluate(el=>el.getBoundingClientRect().height<=518),true,'gallery photography should be reduced by 20 percent');
  assert.equal((await page.locator('.gallery-slide figcaption span:first-child').allTextContents()).join(','),'00 / 10,01 / 10,02 / 10,03 / 10,04 / 10,05 / 10,06 / 10,07 / 10,08 / 10,09 / 10,10 / 10');
  await page.locator('[data-gallery-next]').click();
  await page.waitForTimeout(450);
  assert.equal(await page.locator('[data-gallery-current]').textContent(),'2');
  assert.equal(await page.locator('#field-film source').getAttribute('src'),'/video/new-video.mp4');
  assert.equal(await page.locator('#field-film').evaluate(el=>getComputedStyle(el).objectFit),'contain');
  assert.equal(await page.locator('.field-film').evaluate(el=>el.getBoundingClientRect().width<=701),true,'film should fit with its complete section in one desktop viewport');
  await page.screenshot({path:'/tmp/sound-space-desktop.png',fullPage:true});
  const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
  mobile.on('console',message=>{if(message.type()==='error')errors.push(`mobile: ${message.text()}`);});
  mobile.on('pageerror',error=>errors.push(`mobile: ${error.message}`));
  await mobile.goto(siteUrl,{waitUntil:'networkidle'});
  assert.equal(await mobile.locator('.room-condition').count(),4);
  assert.equal(await mobile.locator('.gallery-slide').count(),11);
  assert.equal(await mobile.locator('body').evaluate(el=>el.scrollWidth<=innerWidth+1),true,'mobile page should not overflow horizontally');
  await mobile.screenshot({path:'/tmp/sound-space-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Redesign verification passed: desktop, interactions, comparison, gallery and mobile.');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
